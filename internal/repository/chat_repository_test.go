package repository

import (
	"testing"
	"time"

	"github.com/google/uuid"
)

func TestChannelBeforeCreateHook(t *testing.T) {
	ch := &Channel{Name: "test-ch", CreatedBy: "u1"}
	if err := ch.BeforeCreate(nil); err != nil {
		t.Fatalf("BeforeCreate failed: %v", err)
	}
	if ch.ID == "" {
		t.Error("expected ID to be generated by BeforeCreate hook")
	}
	if _, err := uuid.Parse(ch.ID); err != nil {
		t.Errorf("invalid UUID generated: %s", ch.ID)
	}
}

