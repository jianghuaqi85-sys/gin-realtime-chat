func TestMessageUpdatedAtFieldExists(t *testing.T) {
	now := time.Now()
	msg := &Message{UpdatedAt: now}
	if msg.UpdatedAt.IsZero() {
		t.Error("expected UpdatedAt field to exist and be populated")
	}
}
